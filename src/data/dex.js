/**
 * Corrections verified against the game itself, which outrank the source.
 * Farigiraf: the site says SpA 107 / SpD 60, but the in-game stat screen for a
 * 0-SpA / 16-SpD Careful spread shows 130 and 116, which only derive from
 * 110/70. See test-team.mjs, which asserts the observed numbers.
 */
export const OVERRIDES = {
  Farigiraf: { spa: 110, spd: 70 },
  // pokebase says 70 HP; pikalytics' Reg M-B page and the canonical line both
  // say 74. Two independent sources beat one.
  Maushold: { hp: 74 },
};

export const DEX = ROWS.map(([name, types, hp, atk, def, spa, spd, spe]) => {
  const base = { hp, atk, def, spa, spd, spe };
  const fix = OVERRIDES[name];
  return {
    name,
    types: String(types).split("/"),
    base: fix ? { ...base, ...fix } : base,
  };
});

const byName = new Map(DEX.map((d) => [d.name.toLowerCase(), d]));

/** Exact (case-insensitive) name lookup. */
export function dexEntry(name) {
  return byName.get(String(name).toLowerCase()) ?? null;
}

/** Does this species Mega Evolve, and into what? */
export function megaOf(name) {
  const direct = dexEntry(`Mega ${name}`);
  if (direct) return direct;
  // Charizard and Raichu have X and Y forms.
  const x = dexEntry(`Mega ${name} X`);
  const y = dexEntry(`Mega ${name} Y`);
  return y ?? x ?? null;
}

/** The pre-Mega species for a "Mega ..." entry. */
export function baseFormOf(megaName) {
  const m = /^Mega\s+(.+?)(?:\s+[XY])?$/.exec(megaName);
  return m ? dexEntry(m[1]) : null;
}

export const DEX_SIZE = DEX.length;
